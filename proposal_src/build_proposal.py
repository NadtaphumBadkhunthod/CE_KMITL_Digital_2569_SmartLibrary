def run(p, text, bold=False, size=None, italic=False):
    r = p.add_run(text)
    if bold: r.bold = True
    if italic: r.italic = True
    r.font.name = FONT
    r._element.rPr.rFonts.set(qn('w:cs'), FONT)
    if size:
        r.font.size = Pt(size)
        sz = OxmlElement('w:szCs'); sz.set(qn('w:val'), str(size * 2))
        r._element.rPr.append(sz)
    return r

def para(text='', bold=False, size=None, align=None, indent_first=True, before=0, after=4):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.space_before, pf.space_after = Pt(before), Pt(after)
    if indent_first:
        pf.first_line_indent = Cm(1.25)
    p.alignment = align if align is not None else WD_ALIGN_PARAGRAPH.THAI_JUSTIFY
    if isinstance(text, str):
        if text: run(p, text, bold, size)
    else:
        for t, b in text:
            run(p, t, b, size)
    return p

def heading(text, size=18, before=12):
    p = para(text, bold=True, size=size, align=WD_ALIGN_PARAGRAPH.LEFT,
             indent_first=False, before=before, after=4)
    p.paragraph_format.keep_with_next = True
    return p

def subheading(text, size=16, before=6):
    p = para(text, bold=True, size=size, align=WD_ALIGN_PARAGRAPH.LEFT,
             indent_first=False, before=before, after=2)
    p.paragraph_format.keep_with_next = True
    return p

def items(lst, marker='•', left=1.9, hang=0.65):
    for i, t in enumerate(lst, 1):
        p = doc.add_paragraph()
        pf = p.paragraph_format
        pf.left_indent = Cm(left)
        pf.first_line_indent = Cm(-hang)
        pf.space_after = Pt(2)
        pf.tab_stops.add_tab_stop(Cm(left))
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        m = f'{i}.' if marker == 'num' else marker
        if isinstance(t, str):
            run(p, f'{m}\t{t}')
        else:
            run(p, f'{m}\t')
            for s, b in t:
                run(p, s, b)

def note(text):
    p = para(text, size=14, align=WD_ALIGN_PARAGRAPH.LEFT, indent_first=False, after=4)
    p.paragraph_format.left_indent = Cm(1.25)
    for r in p.runs:
        r.italic = True
    p.paragraph_format.keep_with_next = False
    return p

def equipment(rows):
    for name, qty in rows:
        p = doc.add_paragraph()
        pf = p.paragraph_format
        pf.left_indent = Cm(1.25)
        pf.space_after = Pt(1)
        pf.tab_stops.add_tab_stop(Cm(11.5))
        run(p, f'- {name}\t{qty}')

def shade(cell, hexcolor):
    tcPr = cell._element.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear'); shd.set(qn('w:color'), 'auto'); shd.set(qn('w:fill'), hexcolor)
    tcPr.append(shd)

def cell_text(cell, text, bold=False, size=15, align=WD_ALIGN_PARAGRAPH.LEFT):
    cell.text = ''
    p = cell.paragraphs[0]
    p.alignment = align
    run(p, text, bold, size)

def cant_split(row):
    trPr = row._tr.get_or_add_trPr()
    el = OxmlElement('w:cantSplit'); trPr.append(el)

